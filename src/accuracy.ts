// How far the estimate can be off, per kind of note, and the margin that the fit test adds.
// The numbers come from a measure against the o200k tokenizer on notes that were not used to tune the estimate
// (BRIEF.md, "Accuracy"). They are estimates of the error, not limits.
import { hasBase64 } from './estimate';

export type NoteClass = 'emoji' | 'base64' | 'cjk' | 'code' | 'table' | 'link';
export type AccuracyClass = NoteClass | 'prose';

export interface ClassStats {
	/** Largest underestimate seen across all holdouts, as a fraction (0.38 = the real count was 38 % higher). */
	under: number;
	/** Error range on the last fresh holdout (holdout3), in percent. Negative is an underestimate. */
	low: number;
	high: number;
}

// Generated by lanes/B2/measure3.mjs (sprint s1119b). The code row adds the 5 code notes of holdout4 (lanes/R1-B2).
export const CLASS_STATS: Record<AccuracyClass, ClassStats> = {
	prose: { under: 0.08, low: -3, high: 9 },
	emoji: { under: 0.38, low: -38, high: -8 },
	base64: { under: 0.24, low: -24, high: -1 },
	cjk: { under: 0.23, low: -23, high: 7 },
	code: { under: 0.12, low: -10, high: 17 },
	table: { under: 0.14, low: -14, high: 11 },
	link: { under: 0.04, low: -4, high: 11 },
};

export const CLASS_NAMES: Record<AccuracyClass, string> = {
	prose: 'plain prose',
	emoji: 'emoji',
	base64: 'base64 data such as embedded images or tokens',
	cjk: 'Chinese, Japanese or Korean text',
	code: 'code blocks',
	table: 'large tables',
	link: 'many links',
};

const WIDE = /[぀-ヿ㐀-䶿一-鿿가-힯ᄀ-ᇿ㄰-㆏豈-﫿]/g;
const ASCII_LETTER = /[A-Za-z]/g;
const LINK = /https?:\/\/\S+|data:[\w/+.-]+;base64,[A-Za-z0-9+/=]+/g;

function count(text: string, re: RegExp): number {
	re.lastIndex = 0;
	let n = 0;
	while (re.exec(text)) n++;
	return n;
}

function emojiCount(text: string): number {
	let n = 0;
	for (let i = 0; i < text.length; i++) {
		const c = text.charCodeAt(i);
		// High surrogates of U+1F000 to U+1FAFF, symbols U+2600 to U+27BF, and keycaps U+20E3.
		if (c === 0xd83c || c === 0xd83d || c === 0xd83e || (c >= 0x2600 && c <= 0x27bf) || c === 0x20e3) n++;
	}
	return n;
}

/** The kinds of content in a note that make the estimate less exact. Empty means plain prose. Linear in the text. */
export function noteClasses(text: string): NoteClass[] {
	const out: NoteClass[] = [];
	if (!text) return out;
	if (emojiCount(text) >= 3) out.push('emoji');
	if (hasBase64(text)) out.push('base64');
	const wide = count(text, WIDE);
	if (wide >= 10 && wide / (wide + count(text, ASCII_LETTER)) >= 0.1) out.push('cjk');
	let lines = 0;
	let rows = 0;
	let codeLines = 0;
	let inFence = false;
	let start = 0;
	while (start <= text.length) {
		let end = text.indexOf('\n', start);
		if (end < 0) end = text.length;
		const line = text.slice(start, end).trim();
		start = end + 1;
		if (line.startsWith('```') || line.startsWith('~~~')) {
			inFence = !inFence;
			codeLines++;
			lines++;
			continue;
		}
		if (!line) continue;
		lines++;
		if (inFence) codeLines++;
		else if (line.startsWith('|')) rows++;
	}
	if (codeLines >= 3 && codeLines / Math.max(1, lines) >= 0.3) out.push('code');
	if (rows >= 3 && rows / Math.max(1, lines) >= 0.3) out.push('table');
	let linkChars = 0;
	LINK.lastIndex = 0;
	for (let m = LINK.exec(text); m; m = LINK.exec(text)) linkChars += m[0].length;
	if (linkChars >= 200 && linkChars / text.length >= 0.3) out.push('link');
	return out;
}

/** The margin for a note, as a fraction. Emoji or base64 content gets the largest margin of all kinds. */
export function marginFor(classes: readonly NoteClass[]): number {
	if (classes.includes('emoji') || classes.includes('base64')) return Math.max(...Object.values(CLASS_STATS).map((s) => s.under));
	let m = CLASS_STATS.prose.under;
	for (const c of classes) m = Math.max(m, CLASS_STATS[c].under);
	return m;
}

/** Tokens to plan for. The estimate is scaled so that the largest measured underestimate still fits.
 * An extra margin in percent from the settings goes on top. */
export function needTokens(tokens: number, classes: readonly NoteClass[], extraPercent = 0): number {
	const u = marginFor(classes);
	return Math.ceil((tokens / (1 - u)) * (1 + Math.max(0, extraPercent) / 100));
}

function range(s: ClassStats): string {
	const f = (x: number): string => (x > 0 ? `${x} % over` : x < 0 ? `${-x} % under` : 'exact');
	return s.low === s.high ? f(s.low) : `between ${f(s.low)} and ${f(s.high)}`;
}

/** One or two sentences about the accuracy of a count, with the measured range of each kind. */
export function accuracyText(classes: readonly NoteClass[] | null | undefined): string {
	const list: AccuracyClass[] = classes?.length ? [...classes] : ['prose'];
	const parts = list.map((c) => `notes with ${CLASS_NAMES[c]} were ${range(CLASS_STATS[c])}`);
	if (!classes?.length) return `This is an estimate. In our test, ${parts[0]}.`;
	return `This is a rough estimate. In our test, ${parts.join(', and ')}.`;
}
